    System.out.println("Minimal\t\t:" + Short.MIN_VALUE);
    System.out.println("Maksimal\t:" + Short.MAX_VALUE);

    // Batas minimal dan maksimal tipe data int
    // Integer.MIN_VALUE konstanta untuk menyimpan nilai minimal tipe data int
    // Integer.MAX_VALUE konstanta untuk menyimpan nilai maksimal tipe data int
    System.out.println("\nBatas minimal dan maksimal tipe data Int");
    System.out.println("Minimal\t\t:" + Integer.MIN_VALUE);
    System.out.println("Maksimal\t:" + Integer.MAX_VALUE);

    // Batas minimal dan maksimal tipe data long
    // Long.MIN_VALUE konstanta untuk menyimpan nilai minimal tipe data long
    // Long.MAX_VALUE konstanta untuk menyimpan nilai maksimal tipe data long
    System.out.println("\nBatas minimal dan maksimal tipe data Long");
    System.out.println("Minimal\t\t:" + Long.MIN_VALUE);
    System.out.println("Maksimal\t:" + Long.MAX_VALUE);

    // Batas minimal dan maksimal tipe data double
    // Double.MIN_VALUE konstanta untuk menyimpan nilai minimal tipe data double
    // Double.MAX_VALUE konstanta untuk menyimpan nilai maksimal tipe data double
    System.out.println("\nBatas minimal dan maksimal tipe data Double");
    System.out.println("Minimal\t\t:" + Double.MIN_VALUE);
    System.out.println("Maksimal\t:" + Double.MAX_VALUE);

    // Batas minimal dan maksimal tipe data float
    // Float.MIN_VALUE konstanta untuk menyimpan nilai minimal tipe data float
    // Float.MAX_VALUE konstanta untuk menyimpan nilai maksimal tipe data float
