public class Day5 {
    public static void main(String[] args) {
        // Tipe data float 32 bit, menyimpan 6 - 7 digit, wajib menggunakan huruf "f" pada akhir angka agar terbaca sebagai tipe data float
        float tinggiBadan = 160.5f;
        System.out.println("Tinggi Badan\t: " + tinggiBadan + " cm");

        // Tipe data double 64 bit, menyimpan 15 - 16 digit
        double beratBadan = 60.55;
        System.out.println("Berat Badan\t: " + beratBadan + " kg");
    }
}
